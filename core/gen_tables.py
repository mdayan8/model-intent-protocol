"""Regenerate src/tables.rs from this Python's unicodedata (mip.py's semantics).
Run: python3 core/gen_tables.py > core/src/tables.rs"""
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for c in range(0x110001):
        ok = c < 0x110000 and pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1)); start = None
    return out

def emit(name, rs):
    print("pub const %s: &[(u32, u32)] = &[" % name)
    for a, b in rs:
        print("    (0x%X, 0x%X)," % (a, b))
    print("];")

print("// Generated by gen_tables.py from Python %s, Unicode %s. Do not edit." % (sys.version.split()[0], unicodedata.unidata_version))
print("// PY_SPACE = str.isspace() (strip() and re \\s); PY_WORD = str.isalnum() or '_' (re \\w, \\b).")
emit("PY_SPACE", ranges(str.isspace))
emit("PY_WORD", ranges(lambda ch: ch.isalnum() or ch == "_"))
